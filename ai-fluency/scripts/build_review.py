"""Validate the term files and generate content/REVIEW.md for human review.

Run from the ai-fluency folder:  python3 scripts/build_review.py
Exits non-zero if any card fails validation, so it can run in CI later.
"""

import json
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TERMS_DIR = ROOT / "content" / "terms"
REVIEW_PATH = ROOT / "content" / "REVIEW.md"

TRACKS = {"fundamentals": "AI fundamentals", "sales-cs": "AI in SaaS sales and CS"}
REQUIRED = ["id", "term", "track", "topic", "plain", "technical", "customerLine",
            "followUp", "misconception", "related", "sources", "status"]
# House style: no em dashes anywhere in card text.
BANNED_CHARS = {"—": "em dash"}

# Domains whose pages were opened and read directly when fact-checking. Every other
# source was confirmed through web search only (the page itself was not reachable
# from the build environment), so it gets flagged for a click-through in review.
READ_DIRECTLY = {"platform.claude.com", "www.anthropic.com"}


def load_terms():
    terms = []
    for path in sorted(TERMS_DIR.glob("*.json")):
        terms.extend(json.loads(path.read_text()))
    return terms


def validate(terms):
    errors = []
    ids = [t.get("id") for t in terms]
    seen = set()
    for i in ids:
        if i in seen:
            errors.append(f"duplicate id: {i}")
        seen.add(i)

    for t in terms:
        tid = t.get("id", "<missing id>")
        for field in REQUIRED:
            if not t.get(field):
                errors.append(f"{tid}: missing {field}")
        if t.get("track") not in TRACKS:
            errors.append(f"{tid}: unknown track {t.get('track')!r}")
        for rel in t.get("related", []):
            if rel not in seen:
                errors.append(f"{tid}: related id {rel!r} does not exist")
        for src in t.get("sources", []):
            if not src.get("url", "").startswith("https://"):
                errors.append(f"{tid}: source without an https url")
        text = json.dumps(t, ensure_ascii=False)
        for char, name in BANNED_CHARS.items():
            if char in text:
                errors.append(f"{tid}: contains an {name}")
    return errors


def domain(url):
    return url.split("/")[2]


def render(terms):
    by_track = defaultdict(lambda: defaultdict(list))
    for t in terms:
        by_track[t["track"]][t["topic"]].append(t)

    flagged = sorted({s["url"] for t in terms for s in t["sources"]
                      if domain(s["url"]) not in READ_DIRECTLY})

    out = [
        "# Content review: starter terms",
        "",
        "_Generated by `scripts/build_review.py` from `content/terms/*.json`. Edit the JSON, not this file._",
        "",
        f"**{len(terms)} terms** across {len(by_track)} tracks. Every card is `draft` until you approve it.",
        "",
        "## How to review",
        "",
        "- Read each card as if a customer asked you the question. Would you be comfortable saying the customer line out loud?",
        "- Tick \"Approved\" when it's good (on GitHub, edit the file and change `[ ]` to `[x]`).",
        "- Leave a note under any card that's wrong, unclear, or doesn't sound like you.",
        "- Lines that tell you to check your own company's facts (\"know your company's real status\") are deliberate: the app shouldn't put claims in your mouth.",
        "",
        "## Sources to click through",
        "",
        "Anthropic pages were opened and read directly. The pages below couldn't be opened from the build environment, so their facts were confirmed through web search instead. Worth a quick click to confirm each link loads:",
        "",
    ]
    out += [f"- <{u}>" for u in flagged]
    out.append("")

    for track, label in TRACKS.items():
        topics = by_track.get(track)
        if not topics:
            continue
        count = sum(len(v) for v in topics.values())
        out += [f"## {label} ({count})", ""]
        for topic, items in topics.items():
            out += [f"### {topic}", ""]
            for t in items:
                aka = f" _(also: {', '.join(t['aka'])})_" if t.get("aka") else ""
                srcs = "; ".join(f"[{s['title']}]({s['url']})" for s in t["sources"])
                flag = ("\n> Needs a better source: the cited page is a general course, "
                        "not a direct definition of this term.\n") if t.get("needsBetterSource") else ""
                out += [
                    f"#### {t['term']}{aka}",
                    "",
                    "- [ ] Approved",
                    flag,
                    f"**Plain English.** {t['plain']}",
                    "",
                    f"**Under the hood.** {t['technical']}",
                    "",
                    f"**Customer line.** \"{t['customerLine']}\"",
                    "",
                    f"**Follow-up:** _{t['followUp']['q']}_ {t['followUp']['a']}",
                    "",
                    f"**Myth:** {t['misconception']['claim']} **Fact:** {t['misconception']['truth']}",
                    "",
                    f"Sources: {srcs}",
                    "",
                ]
    return "\n".join(out)


def main():
    terms = load_terms()
    errors = validate(terms)
    if errors:
        print("Validation failed:")
        for e in errors:
            print(f"  - {e}")
        sys.exit(1)
    REVIEW_PATH.write_text(render(terms))
    print(f"OK: {len(terms)} terms validated, wrote {REVIEW_PATH.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
